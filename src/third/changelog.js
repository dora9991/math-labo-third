// ---- 「まだ見ていない更新」の判定（タイトル画面のお知らせ用） ----
const SEEN_KEY = "mathlabo3.changelogSeen.v1"; // { date, n } … 最後に更新情報を開いた時点の「最新の日付」と「その日の項目数」

/** 最新の更新（これを見たら「見た」とみなす） */
export const LATEST_MARK = { date: CHANGELOG[0].date, n: CHANGELOG[0].items.length };

/** 端末に保存した「見た印」。無ければ null（この仕組みの前から遊んでいる人もここに入る） */
export function loadChangelogSeen() {
  try {
    const o = JSON.parse(localStorage.getItem(SEEN_KEY) || "null");
    if (o && typeof o.date === "string") return { date: o.date, n: Number(o.n) || 0 };
  } catch { /* localStorage が使えない時は「見ていない」のまま */ }
  return null;
}

/** 更新情報を開いた＝最新まで見た、という印を残す */
export function saveChangelogSeen() {
  try { localStorage.setItem(SEEN_KEY, JSON.stringify(LATEST_MARK)); } catch { /* 保存できなくても動く */ }
}

// 見た印が無い端末（この仕組みの前から遊んでいる人も）は、この日までは「見たことにする」。
// 2026-09-30 までは、更新情報のボタンですでにお知らせしていた。これより新しい日だけを「まだ見ていない」にする。
const BASELINE_DATE = "2026-09-30";

/** seen より新しい日（同じ日で項目が増えた日も含む）を、新しい順に返す */
export function unseenChangelogDays(seen = loadChangelogSeen()) {
  if (!seen) return CHANGELOG.filter((d) => d.date > BASELINE_DATE);
  return CHANGELOG.filter((d) => d.date > seen.date || (d.date === seen.date && d.items.length > seen.n));
}
