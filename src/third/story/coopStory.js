/** ステージ index の場面。kind は "pre"（はじまる前）か "post"（勝ったあと）。見つからなければ null。 */
export function coopScene(index, kind) {
  const b = RAID_LADDER[index], st = STAGES[index];
  if (!b || !st) return null;
  const beats = kind === "post" ? st.outro : st.intro;
  return {
    key: `coop:${index}:${kind}`, kind, title: kind === "pre" ? `第${index + 1}話　${st.title}` : `第${index + 1}話　${st.title}（おわり）`,
    bg: chapterBg(b.chapterId), grade: b.grade, chapterId: b.chapterId, enemyId: b.id, beats,
  };
}
export const COOP_STAGE_TITLES = STAGES.map((s) => s.title);
export const COOP_STAGE_COUNT = STAGES.length;
